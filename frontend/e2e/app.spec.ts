import {test,expect} from '@playwright/test'
async function login(page:any){
 await page.request.post('/api/auth/register',{data:{username:'flow_'+Date.now()+'_'+Math.floor(Math.random()*10000),password:'test-pass-123'}})
 await page.goto('/')
 await expect(page.getByRole('heading',{name:'شو أنهيت من خطتك؟'})).toBeVisible()
}
test('course checklist saves before chat and removes proposed section',async({page})=>{
 await login(page)
 await expect(page.getByText('استكشف واختر مقترحك')).toHaveCount(0)
 await page.getByLabel('ابحث عن مساق').fill('10211101')
 await page.getByRole('checkbox').check()
 await page.getByRole('button',{name:'حفظ والمتابعة إلى اسأل دليل'}).click()
 await expect(page.getByText('مساقاً منجزاً محفوظاً في حسابك')).toBeVisible()
 const user=await page.request.get('/api/auth/me')
 expect((await user.json()).completed).toEqual(['10211101'])
 await page.route('**/api/chat',async route=>{expect(route.request().postDataJSON().language).toBe('ar');await route.fulfill({json:{answer:'إجابة للاختبار [1]',status:'answered',sources:[{source_id:'x',document_id:'guide',document_name:'دليل الطالب 2026–2027',page_start:85,article_number:'14',excerpt:'نص المصدر',version:'2026–2027'}],conversation_id:'test',limitations:[],usage:{}}})})
 await page.getByLabel('سؤالك الأكاديمي').fill('شو بقدر أسجل؟')
 await page.getByRole('button',{name:'إرسال السؤال'}).click()
 await expect(page.getByText('المصادر التي استندت إليها الإجابة')).toBeVisible()
 await page.getByRole('button',{name:/دليل الطالب 2026/}).click()
 await expect(page.getByRole('dialog')).toContainText('نص المصدر')
 await expect(page.getByRole('link',{name:'فتح صفحة المصدر'})).toHaveAttribute('href',/page=85/)
})
test('English changes interface and chat language',async({page})=>{
 await login(page)
 await page.getByRole('button',{name:'English',exact:true}).click()
 await expect(page.locator('html')).toHaveAttribute('dir','ltr')
 await expect(page.getByRole('heading',{name:'Which courses have you completed?'})).toBeVisible()
 await page.getByRole('button',{name:'Save & continue to Ask Daleel'}).click()
 await page.route('**/api/chat',async route=>{expect(route.request().postDataJSON().language).toBe('en');await route.fulfill({json:{answer:'Please specify the course.',status:'needs_clarification',sources:[],conversation_id:'test',limitations:[],usage:{}}})})
 await page.getByLabel('Your academic question').fill('Can I register?')
 await page.getByRole('button',{name:'Send question'}).click()
 await expect(page.getByText('Please specify the course.')).toBeVisible()
})
test('friendly errors preserve question',async({page})=>{
 await login(page)
 await page.getByRole('button',{name:'حفظ والمتابعة إلى اسأل دليل'}).click()
 await page.route('**/api/chat',route=>route.fulfill({status:502,json:{detail:'الخدمة مشغولة، حاول مجدداً.'}}))
 await page.getByLabel('سؤالك الأكاديمي').fill('سؤال للاختبار')
 await page.getByRole('button',{name:'إرسال السؤال'}).click()
 await expect(page.getByRole('alert')).toContainText('تعذّر إكمال الطلب')
 await expect(page.getByLabel('سؤالك الأكاديمي')).toHaveValue('سؤال للاختبار')
 await page.getByRole('button',{name:'إغلاق التنبيه'}).click()
 await expect(page.getByRole('alert')).toHaveCount(0)
})
